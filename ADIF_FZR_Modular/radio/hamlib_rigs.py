def marche():
    """Elenco marche, ordinate."""
    return sorted({r[0] for r in RIGS}, key=str.lower)


def modelli(marca):
    """[(modello, codice, stato)] per la marca, ordinati per modello."""
    out = [(m, c, s) for (mk, m, c, s) in RIGS if mk == marca]
    out.sort(key=lambda x: x[0].lower())
    return out


def codice(marca, modello):
    """Codice Hamlib per marca+modello, o None."""
    for (mk, m, c, s) in RIGS:
        if mk == marca and m == modello:
            return c
    return None


def trova(codice_id):
    """(marca, modello, stato) dato il codice, o None."""
    try:
        cid = int(codice_id)
    except Exception:
        return None
    for (mk, m, c, s) in RIGS:
        if c == cid:
            return (mk, m, s)
    return None
