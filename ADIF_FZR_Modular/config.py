def _tema_iniziale():
    """Legge il tema salvato nel profilo default PRIMA di costruire la GUI,
    così l'app parte subito col tema corretto senza flash light→dark."""
    try:
        import os as _os, json as _json
        path = _os.path.join(_os.path.expanduser("~"), ".adif_fzr_profili.json")
        if _os.path.exists(path):
            with open(path, 'r', encoding='utf-8') as f:
                profili = _json.load(f)
            if profili:
                # Profilo default, altrimenti il primo
                dati = next((d for d in profili.values() if d.get('default')), None)
                if dati is None:
                    dati = next(iter(profili.values()))
                if dati.get('pref_ricorda_tema', True):
                    return dati.get('tema', 'System')
    except Exception:
        pass
    return "System"

